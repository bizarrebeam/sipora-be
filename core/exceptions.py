"""
Global Exception Handler for the Django REST Framework.

This module intercepts raised exceptions during request processing and shapes
the resulting HTTP response to match the unified '{status, message, data}' JSON schema.
"""

from rest_framework.views import exception_handler

def core_exception_handler(exc, context):
    """
    Intercepts and standardizes exception payloads generated by API views.
    Ensures absolute structural consistency for error responses consumed by the frontend.
    """
    response = exception_handler(exc, context)
    
    if response is not None:
        message = "Terjadi kesalahan pada sistem."
        data = response.data

        if isinstance(data, dict):
            if "detail" in data:
                message = data.pop("detail")
            else:
                message = "Validasi gagal."
        elif isinstance(data, list):
            message = data[0]

        response.data = {
            "status": "error",
            "message": str(message),
            "data": data if data else None
        }
    return response