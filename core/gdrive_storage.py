"""
Google Drive Storage Backend for Django.

Provides a custom Django file storage that uploads files directly to Google Drive
using a Service Account. Designed for deployment on platforms with ephemeral
filesystems (e.g., Railway) where local media storage is not persistent.

Credentials are loaded from the GDRIVE_SERVICE_ACCOUNT_JSON environment variable
(base64-encoded JSON key) and files are stored under the folder specified by
GDRIVE_ROOT_FOLDER_ID.
"""

import base64
import io
import json
import logging
import os
import uuid
from datetime import datetime

from django.conf import settings
from django.core.files.base import ContentFile
from django.core.files.storage import Storage
from django.utils.deconstruct import deconstructible

logger = logging.getLogger(__name__)


def _build_drive_service():
    """
    Build and return an authenticated Google Drive API service instance.

    Reads the base64-encoded Service Account JSON from the
    GDRIVE_SERVICE_ACCOUNT_JSON setting, decodes it, and constructs
    a Drive v3 API client.

    Returns:
        googleapiclient.discovery.Resource: Authenticated Drive API service.

    Raises:
        ValueError: If GDRIVE_SERVICE_ACCOUNT_JSON is missing or empty.
    """
    from google.oauth2 import service_account
    from googleapiclient.discovery import build

    creds_b64 = getattr(settings, 'GDRIVE_SERVICE_ACCOUNT_JSON', '')
    if not creds_b64:
        raise ValueError(
            'GDRIVE_SERVICE_ACCOUNT_JSON is not configured. '
            'Set it as a base64-encoded Service Account JSON key.'
        )

    creds_json = base64.b64decode(creds_b64)
    creds_info = json.loads(creds_json)

    credentials = service_account.Credentials.from_service_account_info(
        creds_info,
        scopes=['https://www.googleapis.com/auth/drive.file']
    )

    return build('drive', 'v3', credentials=credentials, cache_discovery=False)


@deconstructible
class GoogleDriveStorage(Storage):
    """
    Custom Django Storage Backend that stores files on Google Drive.

    Upload paths generated by Django's ImageField (e.g. 'laporan_kerusakan/<id>/<uuid>.jpg')
    are mapped to a sub-folder hierarchy within the configured root folder on Google Drive.

    Files are made publicly readable so that the returned URL can be used
    directly in <img> tags without further authentication.

    Attributes:
        _root_folder_id (str): The Google Drive folder ID to use as the root.
        _service: Lazily-initialized Google Drive API service.
        _folder_cache (dict): In-memory cache of path → folder ID mappings.
    """

    def __init__(self):
        self._root_folder_id = getattr(settings, 'GDRIVE_ROOT_FOLDER_ID', '')
        self._service = None
        self._folder_cache = {}

    @property
    def service(self):
        """Lazily initialize and return the Google Drive API service."""
        if self._service is None:
            self._service = _build_drive_service()
        return self._service

    def _get_or_create_folder(self, folder_name, parent_id):
        """
        Find or create a folder with the given name under the specified parent.

        Uses an in-memory cache to avoid redundant API calls for the same path.

        Args:
            folder_name (str): Name of the subfolder to find or create.
            parent_id (str): Google Drive ID of the parent folder.

        Returns:
            str: Google Drive ID of the found or newly created folder.
        """
        cache_key = f"{parent_id}/{folder_name}"
        if cache_key in self._folder_cache:
            return self._folder_cache[cache_key]

        # Search for existing folder
        query = (
            f"name = '{folder_name}' and "
            f"'{parent_id}' in parents and "
            f"mimeType = 'application/vnd.google-apps.folder' and "
            f"trashed = false"
        )
        try:
            results = self.service.files().list(
                q=query,
                spaces='drive',
                fields='files(id, name)',
                pageSize=1
            ).execute()

            files = results.get('files', [])
            if files:
                folder_id = files[0]['id']
                self._folder_cache[cache_key] = folder_id
                return folder_id
        except Exception as e:
            logger.warning('Error searching for folder %s: %s', folder_name, e)

        # Create the folder
        file_metadata = {
            'name': folder_name,
            'mimeType': 'application/vnd.google-apps.folder',
            'parents': [parent_id]
        }
        try:
            folder = self.service.files().create(
                body=file_metadata,
                fields='id'
            ).execute()
            folder_id = folder['id']
            self._folder_cache[cache_key] = folder_id
            logger.info('Created Google Drive folder: %s (id=%s)', folder_name, folder_id)
            return folder_id
        except Exception as e:
            logger.error('Failed to create folder %s: %s', folder_name, e)
            raise

    def _ensure_folder_path(self, path_parts):
        """
        Ensure a full folder path exists on Google Drive, creating folders as needed.

        Args:
            path_parts (list[str]): List of folder names forming the path
                (e.g. ['laporan_kerusakan', '<uuid>']).

        Returns:
            str: Google Drive ID of the deepest folder in the path.
        """
        current_parent = self._root_folder_id
        for part in path_parts:
            current_parent = self._get_or_create_folder(part, current_parent)
        return current_parent

    def _generate_filename(self, name):
        """
        Generate a human-readable, timestamp-based filename.

        Preserves the original extension and prepends a timestamp plus
        a short UUID suffix for collision avoidance.

        Args:
            name (str): Original filename (e.g. 'photo.jpg').

        Returns:
            str: Generated filename (e.g. '20260403-232530_a1b2c3.jpg').
        """
        ext = os.path.splitext(name)[1].lower() or '.jpg'
        timestamp = datetime.now().strftime('%Y%m%d-%H%M%S')
        short_id = uuid.uuid4().hex[:6]
        return f"{timestamp}_{short_id}{ext}"

    def _save(self, name, content):
        """
        Save a file to Google Drive.

        Parses the Django upload path to determine the folder hierarchy,
        uploads the file, and makes it publicly readable.

        Args:
            name (str): The full upload path (e.g. 'laporan_kerusakan/<id>/<uuid>.jpg').
            content: A Django File object containing the data to upload.

        Returns:
            str: A storage name in the format 'gdrive://<file_id>/<display_filename>'
                 which is used by url() to reconstruct the public link.
        """
        # Parse the Django upload path: e.g. 'laporan_kerusakan/<id>/<filename>'
        parts = name.replace('\\', '/').split('/')
        if len(parts) > 1:
            folder_parts = parts[:-1]  # All but the last part (the filename)
            original_filename = parts[-1]
        else:
            folder_parts = []
            original_filename = parts[0]

        # Generate a nice filename
        display_name = self._generate_filename(original_filename)

        # Ensure the folder tree exists
        if folder_parts:
            parent_id = self._ensure_folder_path(folder_parts)
        else:
            parent_id = self._root_folder_id

        # Determine MIME type
        ext = os.path.splitext(original_filename)[1].lower()
        mime_map = {
            '.jpg': 'image/jpeg',
            '.jpeg': 'image/jpeg',
            '.png': 'image/png',
            '.webp': 'image/webp',
            '.gif': 'image/gif',
        }
        mime_type = mime_map.get(ext, 'application/octet-stream')

        # Read file content
        content.seek(0)
        file_data = content.read()

        # Upload to Google Drive
        from googleapiclient.http import MediaIoBaseUpload

        file_metadata = {
            'name': display_name,
            'parents': [parent_id]
        }
        media = MediaIoBaseUpload(
            io.BytesIO(file_data),
            mimetype=mime_type,
            resumable=False
        )

        try:
            uploaded = self.service.files().create(
                body=file_metadata,
                media_body=media,
                fields='id, name'
            ).execute()

            file_id = uploaded['id']

            # Make publicly readable
            self.service.permissions().create(
                fileId=file_id,
                body={'type': 'anyone', 'role': 'reader'},
                fields='id'
            ).execute()

            logger.info(
                'Uploaded to Google Drive: %s (id=%s, path=%s)',
                display_name, file_id, '/'.join(folder_parts)
            )

            # Return a composite name that encodes the file_id
            return f"gdrive://{file_id}/{display_name}"

        except Exception as e:
            logger.error('Failed to upload %s to Google Drive: %s', name, e)
            raise

    def url(self, name):
        """
        Return the public URL for a file stored on Google Drive.

        For files stored via this backend (name starts with 'gdrive://'),
        returns a direct download/view URL. Falls back to local media path
        for legacy names.

        Args:
            name (str): The stored file name (e.g. 'gdrive://<file_id>/filename.jpg').

        Returns:
            str: A publicly accessible URL for the file.
        """
        if not name:
            return ''

        if name.startswith('gdrive://'):
            # Format: gdrive://<file_id>/<display_name>
            parts = name[len('gdrive://'):].split('/', 1)
            file_id = parts[0]
            return f"https://drive.google.com/uc?export=view&id={file_id}"

        # Fallback for any legacy local paths
        media_url = getattr(settings, 'MEDIA_URL', '/media/')
        if name.startswith('/'):
            return name
        return f"{media_url}{name}"

    def exists(self, name):
        """
        Check whether a file exists on Google Drive.

        For gdrive:// paths, queries the Drive API. Returns False for
        local paths or on any API error.

        Args:
            name (str): The stored file name.

        Returns:
            bool: True if the file exists, False otherwise.
        """
        if not name or not name.startswith('gdrive://'):
            return False

        parts = name[len('gdrive://'):].split('/', 1)
        file_id = parts[0]

        try:
            self.service.files().get(fileId=file_id, fields='id').execute()
            return True
        except Exception:
            return False

    def delete(self, name):
        """
        Delete a file from Google Drive.

        Only processes gdrive:// paths. Silently ignores local paths
        or API errors (logs a warning instead).

        Args:
            name (str): The stored file name to delete.
        """
        if not name or not name.startswith('gdrive://'):
            return

        parts = name[len('gdrive://'):].split('/', 1)
        file_id = parts[0]

        try:
            self.service.files().delete(fileId=file_id).execute()
            logger.info('Deleted from Google Drive: %s', file_id)
        except Exception as e:
            logger.warning('Failed to delete %s from Google Drive: %s', file_id, e)

    def size(self, name):
        """
        Return the size of a file on Google Drive in bytes.

        Args:
            name (str): The stored file name.

        Returns:
            int: File size in bytes, or 0 on error.
        """
        if not name or not name.startswith('gdrive://'):
            return 0

        parts = name[len('gdrive://'):].split('/', 1)
        file_id = parts[0]

        try:
            file_info = self.service.files().get(
                fileId=file_id, fields='size'
            ).execute()
            return int(file_info.get('size', 0))
        except Exception:
            return 0
